    private static List<Property> properties(Schema schema) {
        JsonNode node = schema.node();
        Path where = Path.of(schema.ref());
        requireOnly(where, node, SCHEMA_KEYWORDS);
        if (!"object".equals(node.path("type").asText()) || !node.path("additionalProperties").isBoolean()
                || node.path("additionalProperties").asBoolean()) {
            throw invalid(where, "a contract schema is an object with additionalProperties false");
        }
        Set<String> required = new LinkedHashSet<>();
        for (JsonNode name : node.path("required")) {
            required.add(name.asText());
        }
        List<Property> properties = new ArrayList<>();
        Iterator<Map.Entry<String, JsonNode>> fields = node.path("properties").properties().iterator();
        while (fields.hasNext()) {
            Map.Entry<String, JsonNode> field = fields.next();
            if (!PROPERTY_NAME.matcher(field.getKey()).matches()) {
                throw invalid(where, "property names are lowerCamelCase: " + field.getKey());
            }
            properties.add(property(where, field.getKey(), field.getValue(), required.remove(field.getKey()), false));
        }
        if (!required.isEmpty()) {
            throw invalid(where, "required names properties it does not define: " + required);
        }
        return List.copyOf(properties);
    }

    private static Property property(Path where, String name, JsonNode node, boolean required, boolean item) {
        requireOnly(where, node, PROPERTY_KEYWORDS);
        String type = node.path("type").asText("");
        String ref = node.path("$ref").asText("");
        Kind kind;
        if (!ref.isEmpty()) {
            if (!type.isEmpty() || !SCHEMA_REF.matcher(ref).matches()) {
                throw invalid(where, name + ": $ref names a brix://schemas/... object and nothing else");
            }
            kind = Kind.OBJECT;
        } else if (node.has("enum")) {
            if (!"string".equals(type)) {
                throw invalid(where, name + ": an enum is a string");
            }
            kind = Kind.ENUM;
        } else {
            kind = switch (type) {
                case "string" -> switch (node.path("format").asText("")) {
                    case "" -> Kind.STRING;
                    case "date-time" -> Kind.INSTANT;
                    case "date" -> Kind.DATE;
                    default -> throw invalid(where, name + ": supported string formats are date-time and date");
                };
                case "integer" -> switch (node.path("format").asText("int64")) {
                    case "int32" -> Kind.INT32;
                    case "int64" -> Kind.INT64;
                    default -> throw invalid(where, name + ": supported integer formats are int32 and int64");
                };
                case "number" -> Kind.NUMBER;
                case "boolean" -> Kind.BOOLEAN;
                case "array" -> Kind.ARRAY;
                default -> throw invalid(where, name + ": unsupported type '" + type + "'");
            };
        }
        List<String> values = new ArrayList<>();
        for (JsonNode value : node.path("enum")) {
            if (!ENUM_VALUE.matcher(value.asText()).matches()) {
                throw invalid(where, name + ": enum values are UPPER_SNAKE: " + value.asText());
            }
            values.add(value.asText());
        }
        Property items = null;
        if (kind == Kind.ARRAY) {
            if (item) {
                throw invalid(where, name + ": arrays do not nest");
            }
            if (!node.has("maxItems")) {
                throw invalid(where, name + ": an array declares maxItems, so a result is bounded (query design §5.6)");
            }
            items = property(where, name, node.path("items"), true, true);
            if (items.kind() == Kind.ENUM) {
                throw invalid(where, name + ": arrays of enums are not supported; use an array of strings");
            }
        }
        String since = node.path("x-brix-since").asText("");
        if (!since.isEmpty() && (required || !VERSION.matcher(since).matches())) {
            throw invalid(where, name + ": x-brix-since marks an optional property added in a later minor version");
        }
        if (!node.path("pattern").asText("").isEmpty()) {
            Pattern.compile(node.path("pattern").asText());
        }
        return new Property(name, node.path("description").asText(""), kind, required, since,
            integer(node, "minLength"), integer(node, "maxLength"), node.path("pattern").asText(""),
            decimal(node, "minimum"), decimal(node, "maximum"), List.copyOf(values), integer(node, "minItems"),
            integer(node, "maxItems"), items, ref);
    }

    /**
     * Root BRX-RS-CAP-019, CAP-020: within a major version a later schema keeps every earlier property as it was,
     * in the same order, and adds only optional properties after them, marked with the version that added them.
     */
    private static void checkCompatible(Schema newest, List<Schema> history, List<List<Property>> versions) {
        for (int i = 1; i < versions.size(); i++) {
            List<Property> before = versions.get(i - 1);
            List<Property> after = versions.get(i);
            String version = history.get(i).version();
            if (after.size() < before.size()) {
                throw new IllegalArgumentException(newest.name() + " " + version + " removes properties of "
                    + history.get(i - 1).version() + "; a breaking change needs a new major version");
            }
            for (int p = 0; p < after.size(); p++) {
                Property property = after.get(p);
                if (p < before.size()) {
                    if (!before.get(p).signature().equals(property.signature())) {
                        throw new IllegalArgumentException(newest.name() + " " + version + " changes property "
                            + property.name() + " of " + history.get(i - 1).version() + " (" + before.get(p).signature()
                            + " to " + property.signature() + "); a breaking change needs a new major version");
                    }
                } else if (property.required() || compare(property.since(), version) > 0
                        || compare(property.since(), history.get(i - 1).version()) <= 0) {
                    throw new IllegalArgumentException(newest.name() + " " + version + " adds property "
                        + property.name() + ", which must be optional and marked x-brix-since: \"" + version + "\"");
                }
            }
        }
        for (Property property : versions.get(0)) {
            if (!property.since().isEmpty()) {
                throw new IllegalArgumentException(newest.name() + " " + history.get(0).version() + " marks "
                    + property.name() + " with x-brix-since, but it was there from the first version of its major");
            }
        }
    }

