    private enum Kind {
        STRING, INSTANT, DATE, INT32, INT64, NUMBER, BOOLEAN, ENUM, OBJECT, ARRAY
    }

    private record Schema(String ref, JsonNode node) {

        String plugin() {
            return part(1);
        }

        String name() {
            return part(2);
        }

        String version() {
            return part(3);
        }

        int major() {
            return Integer.parseInt(part(4));
        }

        private String part(int group) {
            Matcher matcher = SCHEMA_REF.matcher(ref);
            if (!matcher.matches()) {
                throw new IllegalArgumentException("not a schema reference: " + ref);
            }
            return matcher.group(group);
        }
    }

    private record Contract(String queryType, String version, String request, String response, boolean optional,
            String description) {

        String plugin() {
            return queryType.substring(0, queryType.indexOf('.'));
        }

        int major() {
            return Integer.parseInt(version.substring(0, version.indexOf('.')));
        }

        String constant() {
            String name = constant(queryType.substring(queryType.indexOf('.') + 1));
            return major() > 1 ? name + "_V" + major() : name;
        }

        String api(String constants, Map<String, Type> types) {
            return "query " + constants + "." + constant() + " = " + queryType + " major " + major() + " "
                + (optional ? "optional " : "required ") + typeOf(request, types) + " -> " + typeOf(response, types);
        }

        private static String constant(String name) {
            return QueryContractGenerator.constant(name);
        }
    }

    private record CommandContract(String commandType, String version, String request, String description) {

        String plugin() {
            return commandType.substring(0, commandType.indexOf('.'));
        }

        int major() {
            return Integer.parseInt(version.substring(0, version.indexOf('.')));
        }

        String constant() {
            String name = QueryContractGenerator.constant(commandType.substring(commandType.indexOf('.') + 1));
            return major() > 1 ? name + "_V" + major() : name;
        }

        String api(String constants, Map<String, Type> types) {
            return "command " + constants + "." + constant() + " = " + commandType + " major " + major() + " "
                + typeOf(request, types);
        }
    }

    private record Type(String key, Schema schema, String className, List<Schema> history,
            List<List<Property>> versions) {

        List<Property> current() {
            return versions.get(versions.size() - 1);
        }

        List<String> api(Map<String, Type> types) {
            List<String> lines = new ArrayList<>();
            lines.add("record " + className + " schema " + schema.plugin() + "/" + schema.name() + " major "
                + schema.major());
            Set<Integer> arities = new TreeSet<>(Comparator.reverseOrder());
            for (List<Property> version : versions) {
                arities.add(version.size());
            }
            for (int arity : arities) {
                List<String> parameterTypes = new ArrayList<>();
                for (Property property : current().subList(0, arity)) {
                    parameterTypes.add(property.javaType(types));
                }
                lines.add("constructor " + className + "(" + String.join(", ", parameterTypes) + ")");
            }
            for (Property property : current()) {
                lines.add("accessor " + className + "." + property.name() + "(): " + property.javaType(types)
                    + (property.required() ? " required" : " optional"));
                lines.add("builder " + className + ".Builder." + property.name() + "(" + property.boxedType(types) + ")");
                for (String value : property.enumValues()) {
                    lines.add("enum " + className + "." + pascal(property.name()) + "." + value);
                }
            }
            return lines;
        }
    }

    private record Property(String name, String description, Kind kind, boolean required, String since,
            Integer minLength, Integer maxLength, String pattern, BigDecimal minimum, BigDecimal maximum,
            List<String> enumValues, Integer minItems, Integer maxItems, Property items, String ref) {

        /** Everything a later minor version must keep. */
        String signature() {
            String target = kind == Kind.OBJECT ? refKey(ref) : "";
            return kind + (required ? " required" : " optional") + " len[" + minLength + "," + maxLength + "] pattern["
                + pattern + "] range[" + minimum + "," + maximum + "] enum" + enumValues + " items[" + minItems + ","
                + maxItems + "]" + (items == null ? "" : " of(" + items.signature() + ")") + target;
        }

        boolean primitive() {
            return required && (kind == Kind.INT32 || kind == Kind.INT64 || kind == Kind.BOOLEAN);
        }

        String javaType(Map<String, Type> types) {
            if (primitive()) {
                return switch (kind) {
                    case INT32 -> "int";
                    case INT64 -> "long";
                    default -> "boolean";
                };
            }
            return boxedType(types);
        }

        String boxedType(Map<String, Type> types) {
            return switch (kind) {
                case STRING -> "String";
                case INSTANT -> "Instant";
                case DATE -> "LocalDate";
                case INT32 -> "Integer";
                case INT64 -> "Long";
                case NUMBER -> "BigDecimal";
                case BOOLEAN -> "Boolean";
                case ENUM -> pascal(name);
                case OBJECT -> typeOf(ref, types);
                case ARRAY -> "List<" + items.boxedType(types) + ">";
            };
        }

        Set<String> imports() {
            Set<String> imports = new TreeSet<>();
            Property target = kind == Kind.ARRAY ? items : this;
            if (kind == Kind.ARRAY) {
                imports.add("java.util.List");
            }
            switch (target.kind()) {
                case INSTANT -> imports.add("java.time.Instant");
                case DATE -> imports.add("java.time.LocalDate");
                case NUMBER -> imports.add("java.math.BigDecimal");
                default -> {
                }
            }
            return imports;
        }

        void validation(Java java) {
            String indent = "        ";
            if (required && !primitive()) {
                java.line(indent + "Objects.requireNonNull(" + name + ", \"" + name + " must not be null\");");
            }
            if (kind == Kind.ARRAY) {
                java.line(indent + "if (" + name + " != null) {");
                java.line(indent + "    " + name + " = List.copyOf(" + name + ");");
                if (maxItems != null) {
                    java.line(indent + "    if (" + name + ".size() > " + maxItems + ") {");
                    java.line(indent + "        throw new IllegalArgumentException(\"" + name + " holds at most " + maxItems
                        + " items\");");
                    java.line(indent + "    }");
                }
                if (minItems != null) {
                    java.line(indent + "    if (" + name + ".size() < " + minItems + ") {");
                    java.line(indent + "        throw new IllegalArgumentException(\"" + name + " holds at least " + minItems
                        + " items\");");
                    java.line(indent + "    }");
                }
                if (items.hasChecks()) {
                    java.line(indent + "    for (" + "var item : " + name + ") {");
                    items.checks(java, indent + "        ", "item", constant(name) + "_ITEM_PATTERN", name + " item");
                    java.line(indent + "    }");
                }
                java.line(indent + "}");
                return;
            }
            if (!hasChecks()) {
                return;
            }
            if (primitive()) {
                checks(java, indent, name, constant(name) + "_PATTERN", name);
            } else {
                java.line(indent + "if (" + name + " != null) {");
                checks(java, indent + "    ", name, constant(name) + "_PATTERN", name);
                java.line(indent + "}");
            }
        }

        boolean hasChecks() {
            return minLength != null || maxLength != null || !pattern.isEmpty() || minimum != null || maximum != null;
        }

        void checks(Java java, String indent, String value, String patternConstant, String label) {
            if (minLength != null) {
                java.line(indent + "if (" + value + ".length() < " + minLength + ") {");
                java.line(indent + "    throw new IllegalArgumentException(\"" + label + " is at least " + minLength
                    + " characters\");");
                java.line(indent + "}");
            }
            if (maxLength != null) {
                java.line(indent + "if (" + value + ".length() > " + maxLength + ") {");
                java.line(indent + "    throw new IllegalArgumentException(\"" + label + " is at most " + maxLength
                    + " characters\");");
                java.line(indent + "}");
            }
            if (!pattern.isEmpty()) {
                java.line(indent + "if (!" + patternConstant + ".matcher(" + value + ").matches()) {");
                java.line(indent + "    throw new IllegalArgumentException(\"" + label + " does not match its pattern\");");
                java.line(indent + "}");
            }
            if (minimum != null) {
                java.line(indent + "if (" + compareBelow(value, minimum) + ") {");
                java.line(indent + "    throw new IllegalArgumentException(\"" + label + " is at least " + minimum.toPlainString()
                    + "\");");
                java.line(indent + "}");
            }
            if (maximum != null) {
                java.line(indent + "if (" + compareAbove(value, maximum) + ") {");
                java.line(indent + "    throw new IllegalArgumentException(\"" + label + " is at most " + maximum.toPlainString()
                    + "\");");
                java.line(indent + "}");
            }
        }

        private String compareBelow(String value, BigDecimal bound) {
            return kind == Kind.NUMBER
                ? value + ".compareTo(new BigDecimal(\"" + bound.toPlainString() + "\")) < 0"
                : value + " < " + bound.toBigIntegerExact() + (kind == Kind.INT64 ? "L" : "");
        }

        private String compareAbove(String value, BigDecimal bound) {
            return kind == Kind.NUMBER
                ? value + ".compareTo(new BigDecimal(\"" + bound.toPlainString() + "\")) > 0"
                : value + " > " + bound.toBigIntegerExact() + (kind == Kind.INT64 ? "L" : "");
        }

        private static String refKey(String ref) {
            Matcher matcher = SCHEMA_REF.matcher(ref);
            return matcher.matches() ? " ref " + matcher.group(1) + "/" + matcher.group(2) + "#" + matcher.group(4) : ref;
        }
    }

    /** A source being written. */
    private static final class Java {

        private final StringBuilder text = new StringBuilder();

        void header(String from, String javaPackage) {
            line("/*");
            line(" * " + GENERATED_MARK + " from " + from + ".");
            line(" * Do not edit: change the schema and regenerate.");
            line(" */");
            line("package " + javaPackage + ";");
            blank();
        }

        void imports(Set<String> imports) {
            List<String> java = imports.stream().filter(name -> name.startsWith("java.")).sorted().toList();
            List<String> other = imports.stream().filter(name -> !name.startsWith("java.")).sorted().toList();
            for (String name : java) {
                line("import " + name + ";");
            }
            if (!java.isEmpty() && !other.isEmpty()) {
                blank();
            }
            for (String name : other) {
                line("import " + name + ";");
            }
            blank();
        }

        void doc(String prefix, String text) {
            line(prefix + escapeDoc(text));
        }

        void line(String line) {
            text.append(line).append('\n');
        }

        void blank() {
            text.append('\n');
        }

        @Override
        public String toString() {
            return text.toString();
        }
    }

