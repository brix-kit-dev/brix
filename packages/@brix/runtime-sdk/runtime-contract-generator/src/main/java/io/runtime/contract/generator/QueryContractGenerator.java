    private static List<Path> jsonFiles(Path root) {
        if (!Files.isDirectory(root)) {
            return List.of();
        }
        try (Stream<Path> files = Files.walk(root)) {
            return files.filter(file -> file.toString().endsWith(".json")).sorted().toList();
        } catch (IOException unreadable) {
            throw new UncheckedIOException(unreadable);
        }
    }

    private static JsonNode read(Path file) {
        try {
            return JSON.readTree(Files.readString(file));
        } catch (IOException unreadable) {
            throw new UncheckedIOException("cannot read " + file, unreadable);
        } catch (RuntimeException malformed) {
            throw invalid(file, "is not valid JSON: " + malformed.getMessage());
        }
    }

    private static void requireOnly(Path where, JsonNode node, Set<String> allowed) {
        Iterator<String> names = node.propertyNames().iterator();
        while (names.hasNext()) {
            String name = names.next();
            if (!allowed.contains(name)) {
                throw invalid(where, "uses '" + name + "', which the contract generator does not support");
            }
        }
    }

    private static Integer integer(JsonNode node, String field) {
        return node.has(field) ? node.path(field).asInt() : null;
    }

    private static BigDecimal decimal(JsonNode node, String field) {
        return node.has(field) ? new BigDecimal(node.path(field).asText()) : null;
    }

    private static String stripJson(String file) {
        return file.endsWith(".json") ? file.substring(0, file.length() - 5) : file;
    }

    private static int compare(String a, String b) {
        if (a.isEmpty() || b.isEmpty()) {
            return a.isEmpty() ? (b.isEmpty() ? 0 : -1) : 1;
        }
        String[] left = a.split("\\.");
        String[] right = b.split("\\.");
        for (int i = 0; i < 3; i++) {
            int difference = Integer.compare(Integer.parseInt(left[i]), Integer.parseInt(right[i]));
            if (difference != 0) {
                return difference;
            }
        }
        return 0;
    }

    static String pascal(String name) {
        StringBuilder result = new StringBuilder();
        boolean upper = true;
        for (char c : name.toCharArray()) {
            if (c == '-' || c == '_') {
                upper = true;
            } else if (upper) {
                result.append(Character.toUpperCase(c));
                upper = false;
            } else {
                result.append(c);
            }
        }
        return result.toString();
    }

    static String constant(String name) {
        return name.replaceAll("([a-z0-9])([A-Z])", "$1_$2").replace('-', '_').toUpperCase(java.util.Locale.ROOT);
    }

    private static String literal(String value) {
        StringBuilder result = new StringBuilder("\"");
        for (char c : value.toCharArray()) {
            switch (c) {
                case '\\' -> result.append("\\\\");
                case '"' -> result.append("\\\"");
                case '\n' -> result.append("\\n");
                default -> result.append(c);
            }
        }
        return result.append('"').toString();
    }

    private static String escapeDoc(String text) {
        return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("*/", "*&#47;");
    }

    private static IllegalArgumentException invalid(Path where, String reason) {
        return new IllegalArgumentException(where + ": " + reason);
    }

